-- MSA PORTAL announcement table.
-- REVIEW ONLY: do not execute against production Neon until approved.
CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_type TEXT NOT NULL
        CHECK (announcement_type IN ('results_coming_soon', 'results_are_out')),
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_by TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE INDEX IF NOT EXISTS idx_announcements_active_created
    ON announcements (active, created_at DESC);
