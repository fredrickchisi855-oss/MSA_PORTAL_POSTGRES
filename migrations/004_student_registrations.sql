-- MSA PORTAL student registration review queue.
-- Additive schema only. Test separately before production use.

CREATE TABLE IF NOT EXISTS student_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    normalized_name TEXT NOT NULL,
    form INTEGER NOT NULL CHECK (form BETWEEN 1 AND 6),
    class_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    review_reason TEXT,
    matched_student_id BIGINT REFERENCES students(id),
    approved_student_id BIGINT REFERENCES students(id),
    reviewed_by TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    reviewed_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_student_registrations_status_created
    ON student_registrations (status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_student_registrations_name_form
    ON student_registrations (normalized_name, form);
