-- MSA PORTAL PostgreSQL core schema.
-- REVIEW ONLY. Do not execute against production without approval.
-- Text timestamps are retained for compatibility with the existing
-- SQLite-oriented application. Validate all columns against server.py
-- and test against a separate PostgreSQL database before deployment.

BEGIN;

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    form INTEGER NOT NULL CHECK (form BETWEEN 1 AND 6),
    class_name TEXT NOT NULL,
    password TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Active',
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    student_id_code TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_students_student_id_code
    ON students (student_id_code);

CREATE TABLE IF NOT EXISTS academic_years (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL UNIQUE,
    active INTEGER NOT NULL DEFAULT 0
        CHECK (active IN (0, 1))
);

INSERT INTO academic_years (year, active)
VALUES (2026, 1), (2027, 0), (2028, 0), (2029, 0), (2030, 0)
ON CONFLICT (year) DO NOTHING;

CREATE TABLE IF NOT EXISTS admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'admin',
    password_hash TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    academic_year INTEGER NOT NULL,
    term TEXT NOT NULL,
    file_name TEXT,
    file_path TEXT,
    published INTEGER NOT NULL DEFAULT 0
        CHECK (published IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE INDEX IF NOT EXISTS idx_results_student_year_term
    ON results (student_id, academic_year, term);

CREATE TABLE IF NOT EXISTS password_reset_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    status TEXT NOT NULL DEFAULT 'pending',
    reset_pin TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    approved_at TEXT,
    expires_at TEXT,
    used_at TEXT,
    student_name TEXT,
    student_id_code TEXT,
    student_form INTEGER,
    student_class_name TEXT,
    is_new INTEGER NOT NULL DEFAULT 1
        CHECK (is_new IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_reset_requests_student_status
    ON password_reset_requests (student_id, status);

CREATE TABLE IF NOT EXISTS student_login_security (
    student_id BIGINT PRIMARY KEY REFERENCES students(id),
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    blocked INTEGER NOT NULL DEFAULT 0 CHECK (blocked IN (0, 1)),
    blocked_at TEXT,
    last_failed_at TEXT
);

CREATE TABLE IF NOT EXISTS password_reset_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT,
    student_name TEXT,
    student_id_code TEXT,
    form INTEGER,
    entered_student_id TEXT,
    result TEXT NOT NULL,
    reason TEXT,
    request_id BIGINT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

COMMIT;
