import getpass
import sqlite3
import sys
from pathlib import Path

import psycopg


SOURCE = Path.home() / "MSA_PORTAL/backend/msa_portal.db"

TABLES = [
    "academic_years",
    "admin_users",
    "students",
    "results",
    "password_reset_requests",
    "password_reset_attempts",
    "student_login_security",
]

# PostgreSQL schema for the confirmed SQLite tables.
SCHEMA = [
    """
    CREATE TABLE academic_years (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        year INTEGER NOT NULL UNIQUE,
        active INTEGER NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE admin_users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        display_name TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'admin',
        password_hash TEXT NOT NULL,
        active INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        last_login_at TEXT
    )
    """,
    """
    CREATE TABLE students (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        form INTEGER NOT NULL CHECK (form BETWEEN 1 AND 6),
        class_name TEXT NOT NULL,
        password TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'Active',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        student_id_code TEXT
    )
    """,
    """
    CREATE TABLE results (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id INTEGER NOT NULL REFERENCES students(id),
        academic_year INTEGER NOT NULL,
        term TEXT NOT NULL,
        file_name TEXT,
        file_path TEXT,
        published INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE password_reset_requests (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id INTEGER NOT NULL REFERENCES students(id),
        status TEXT NOT NULL DEFAULT 'pending',
        reset_pin TEXT,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        approved_at TEXT,
        expires_at TEXT,
        used_at TEXT,
        student_name TEXT,
        student_id_code TEXT,
        student_form INTEGER,
        student_class_name TEXT,
        is_new INTEGER NOT NULL DEFAULT 1
    )
    """,
    """
    CREATE TABLE password_reset_attempts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id INTEGER,
        student_name TEXT,
        student_id_code TEXT,
        form INTEGER,
        entered_student_id TEXT,
        result TEXT NOT NULL,
        reason TEXT,
        request_id INTEGER,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE student_login_security (
        student_id INTEGER PRIMARY KEY REFERENCES students(id),
        failed_attempts INTEGER NOT NULL DEFAULT 0,
        blocked INTEGER NOT NULL DEFAULT 0,
        blocked_at TEXT,
        last_failed_at TEXT
    )
    """,
]

INDEXES = [
    "CREATE INDEX idx_admin_users_username ON admin_users(username)",
    """
    CREATE INDEX idx_reset_attempts_created
    ON password_reset_attempts(created_at)
    """,
    """
    CREATE INDEX idx_reset_attempts_result
    ON password_reset_attempts(result)
    """,
    """
    CREATE INDEX idx_reset_attempts_student
    ON password_reset_attempts(student_id)
    """,
    """
    CREATE INDEX idx_reset_requests_is_new
    ON password_reset_requests(is_new)
    """,
    """
    CREATE UNIQUE INDEX idx_students_student_id_code
    ON students(student_id_code)
    """,
]


def main():
    if not SOURCE.is_file():
        sys.exit(f"STOP: Source database not found: {SOURCE}")

    source = sqlite3.connect(
        f"file:{SOURCE}?mode=ro",
        uri=True,
    )
    source.row_factory = sqlite3.Row

    target = None

    try:
        integrity = source.execute(
            "PRAGMA integrity_check"
        ).fetchone()[0]

        if integrity != "ok":
            sys.exit(f"STOP: SQLite integrity check failed: {integrity}")

        source_counts = {}

        print("\nMSA PORTAL — MIGRATION PRE-CHECK")
        print("Source:", SOURCE)

        for table in TABLES:
            exists = source.execute(
                """
                SELECT 1 FROM sqlite_master
                WHERE type = 'table' AND name = ?
                """,
                (table,),
            ).fetchone()

            if not exists:
                sys.exit(f"STOP: Required source table missing: {table}")

            source_counts[table] = source.execute(
                f'SELECT COUNT(*) FROM "{table}"'
            ).fetchone()[0]

            print(f"{table}: {source_counts[table]} records")

        total = sum(source_counts.values())
        print("Total source records:", total)

        if total != 36:
            sys.exit(
                "STOP: Source total differs from the verified baseline "
                "of 36 records. Review before migrating."
            )

        # URL entry is hidden; it is not printed by this script.
        print("\nEnter the NEW Neon connection string.")
        print("Input will be hidden. Do not share it in chat.")
        url = getpass.getpass("Neon DATABASE_URL: ").strip()

        if not url:
            sys.exit("STOP: No connection string supplied.")

        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://"):]

        target = psycopg.connect(url)

        # Never overwrite or merge into an existing target schema.
        existing = target.execute(
            """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'public'
              AND table_type = 'BASE TABLE'
            ORDER BY table_name
            """
        ).fetchall()

        if existing:
            print("\nSTOP: Neon already contains public tables:")
            for row in existing:
                print("-", row[0])
            print("No migration was performed.")
            target.rollback()
            return

        print("\nNeon connected; public schema is empty.")
        print("Creating schema and copying records...")

        # All table creation, data insertion, indexes and verification
        # happen in one transaction. A failure rolls everything back.
        for statement in SCHEMA:
            target.execute(statement)

        for table in TABLES:
            columns = [
                row[1]
                for row in source.execute(
                    f'PRAGMA table_info("{table}")'
                ).fetchall()
            ]

            quoted_columns = ", ".join(
                '"' + column.replace('"', '""') + '"'
                for column in columns
            )
            placeholders = ", ".join(["%s"] * len(columns))

            rows = source.execute(
                f'SELECT * FROM "{table}"'
            ).fetchall()

            if rows:
                insert_sql = (
                    f'INSERT INTO "{table}" ({quoted_columns}) '
                    f'VALUES ({placeholders})'
                )
                target.cursor().executemany(
                    insert_sql,
                    [tuple(row[column] for column in columns) for row in rows],
                )

            print(f"Copied {table}: {len(rows)} records")

        for statement in INDEXES:
            target.execute(statement)

        # Restore generated-ID sequences after importing explicit IDs.
        identity_tables = [
            "academic_years",
            "admin_users",
            "students",
            "results",
            "password_reset_requests",
            "password_reset_attempts",
        ]

        for table in identity_tables:
            maximum = target.execute(
                f'SELECT MAX(id) FROM "{table}"'
            ).fetchone()[0]

            if maximum is not None:
                target.execute(
                    "SELECT setval("
                    f"pg_get_serial_sequence('public.{table}', 'id'), "
                    "%s, true)",
                    (maximum,),
                )

        print("\n===== VERIFYING BEFORE COMMIT =====")
        destination_counts = {}
        for table in TABLES:
            count = target.execute(
                f'SELECT COUNT(*) FROM "{table}"'
            ).fetchone()[0]
            destination_counts[table] = count

            print(
                f"{table}: source={source_counts[table]}, "
                f"Neon={count}"
            )

            if count != source_counts[table]:
                raise RuntimeError(
                    f"Count mismatch in {table}; transaction cancelled."
                )

        destination_total = sum(destination_counts.values())
        if destination_total != total:
            raise RuntimeError(
                "Total record mismatch; transaction cancelled."
            )

        # Extra relationship checks.
        checks = {
            "results without students": """
                SELECT COUNT(*) FROM results r
                LEFT JOIN students s ON s.id = r.student_id
                WHERE s.id IS NULL
            """,
            "reset requests without students": """
                SELECT COUNT(*) FROM password_reset_requests r
                LEFT JOIN students s ON s.id = r.student_id
                WHERE s.id IS NULL
            """,
            "security rows without students": """
                SELECT COUNT(*) FROM student_login_security l
                LEFT JOIN students s ON s.id = l.student_id
                WHERE s.id IS NULL
            """,
        }

        for label, query in checks.items():
            count = target.execute(query).fetchone()[0]
            print(f"{label}: {count}")
            if count:
                raise RuntimeError(
                    f"Relationship check failed: {label}"
                )

        target.commit()

        print("\nSUCCESS: Migration committed.")
        print("Total records copied and verified:", destination_total)
        print("Original SQLite database was opened read-only.")
        print("Result PDFs were not moved or modified.")
        print("Keep the new Neon connection string private.")

    except Exception as exc:
        if target is not None:
            target.rollback()
        print("\nMIGRATION STOPPED; target transaction rolled back.")
        print("Reason:", str(exc))
        sys.exit(1)

    finally:
        source.close()
        if target is not None:
            target.close()


if __name__ == "__main__":
    main()
