"""Dual database compatibility for MSA PORTAL."""

import os
import re
import sqlite3
from pathlib import Path


BASE_DIR = Path(__file__).resolve().parent
SQLITE_FILE = Path(
    os.environ.get("MSA_SQLITE_PATH", str(BASE_DIR / "msa_portal.db"))
)


def using_postgres():
    return bool(os.environ.get("DATABASE_URL", "").strip())


class HybridRow:
    """Row supporting both SQLite-style numeric and named indexing."""

    def __init__(self, names, values):
        self._names = tuple(names)
        self._values = tuple(values)
        self._mapping = dict(zip(self._names, self._values))

    def __getitem__(self, key):
        if isinstance(key, str):
            return self._mapping[key]
        return self._values[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def keys(self):
        return self._names

    def get(self, key, default=None):
        return self._mapping.get(key, default)


def _postgres_sql(sql):
    """Translate the SQLite syntax used by this application."""

    sql = sql.strip().rstrip(";")

    # Translate SQLite table inspection using a fixed table allowlist.
    pragma_match = re.match(
        r"^\s*PRAGMA\s+table_info\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*$",
        sql,
        re.IGNORECASE,
    )

    if pragma_match:
        table_name = pragma_match.group(1).lower()
        allowed_tables = {
            "students",
            "admin_users",
            "academic_years",
            "results",
            "password_reset_requests",
            "student_login_security",
            "password_reset_attempts",
        }
        if table_name not in allowed_tables:
            raise ValueError(f"Unsupported table_info request: {table_name}")

        sql = """
            SELECT
                c.ordinal_position - 1 AS cid,
                c.column_name AS name,
                c.data_type AS type,
                CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
                c.column_default AS dflt_value,
                CASE WHEN EXISTS (
                    SELECT 1
                    FROM information_schema.table_constraints tc
                    JOIN information_schema.key_column_usage kcu
                      ON tc.constraint_catalog = kcu.constraint_catalog
                     AND tc.constraint_schema = kcu.constraint_schema
                     AND tc.constraint_name = kcu.constraint_name
                    WHERE tc.constraint_type = 'PRIMARY KEY'
                      AND tc.table_schema = c.table_schema
                      AND tc.table_name = c.table_name
                      AND kcu.column_name = c.column_name
                ) THEN 1 ELSE 0 END AS pk
            FROM information_schema.columns c
            WHERE c.table_schema = current_schema()
              AND c.table_name = %s
            ORDER BY c.ordinal_position
        """
        return sql, (table_name,)

    ignore_insert = bool(
        re.match(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", sql, re.IGNORECASE)
    )

    if ignore_insert:
        sql = re.sub(
            r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b",
            "INSERT INTO",
            sql,
            count=1,
            flags=re.IGNORECASE,
        )

    # Preserve case-insensitive matching and ordering.
    sql = re.sub(
        r"\b([A-Za-z_][\w.]*)\s*=\s*(\?)\s+COLLATE\s+NOCASE",
        r"LOWER(\1) = LOWER(\2)",
        sql,
        flags=re.IGNORECASE,
    )

    sql = re.sub(
        r"\b([A-Za-z_][\w.]*)\s+COLLATE\s+NOCASE",
        r"LOWER(\1)",
        sql,
        flags=re.IGNORECASE,
    )

    # PostgreSQL identity column syntax.
    sql = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sql,
        flags=re.IGNORECASE,
    )

    # Convert placeholders used throughout the existing server.
    sql = sql.replace("?", "%s")

    # The application's INSERT OR IGNORE is used for academic years.
    if ignore_insert:
        sql += " ON CONFLICT DO NOTHING"

    # These inserts require a generated ID later in the existing code.
    if re.match(
        r"^\s*INSERT\s+INTO\s+(students|results|password_reset_requests)\b",
        sql,
        re.IGNORECASE,
    ) and not re.search(r"\bRETURNING\b", sql, re.IGNORECASE):
        sql += " RETURNING id"

    return sql


class CompatibleCursor:
    def __init__(self, raw_cursor):
        self._raw = raw_cursor
        self._cached = None
        self.lastrowid = None

    @property
    def rowcount(self):
        return self._raw.rowcount

    @property
    def description(self):
        return self._raw.description

    def execute(self, sql, parameters=()):
        self._cached = None
        self.lastrowid = None

        translated = _postgres_sql(sql)

        # Schema-inspection translations can supply their own parameters.
        if isinstance(translated, tuple):
            translated, parameters = translated

        needs_id = bool(
            re.search(r"\bRETURNING\s+id\s*$", translated, re.IGNORECASE)
            and re.match(r"^\s*INSERT\b", translated, re.IGNORECASE)
        )

        self._raw.execute(translated, parameters)

        if needs_id:
            row = self._raw.fetchone()
            if row is not None:
                self.lastrowid = row[0]
                self._cached = row

        return self

    def executemany(self, sql, parameters):
        self._cached = None
        self.lastrowid = None

        translated = _postgres_sql(sql)
        if isinstance(translated, tuple):
            translated, _ = translated
            raise ValueError(
                "Schema-inspection queries cannot use executemany()."
            )

        self._raw.executemany(translated, parameters)
        return self

    def _convert(self, row):
        if row is None:
            return None
        names = [column.name for column in self._raw.description]
        return HybridRow(names, row)

    def fetchone(self):
        if self._cached is not None:
            row = self._cached
            self._cached = None
        else:
            row = self._raw.fetchone()
        return self._convert(row)

    def fetchall(self):
        rows = []
        if self._cached is not None:
            rows.append(self._cached)
            self._cached = None
        rows.extend(self._raw.fetchall())
        return [self._convert(row) for row in rows]

    def __iter__(self):
        while True:
            row = self.fetchone()
            if row is None:
                break
            yield row


class CompatibleConnection:
    def __init__(self, raw):
        self._raw = raw

    def cursor(self):
        return CompatibleCursor(self._raw.cursor())

    def execute(self, sql, parameters=()):
        return self.cursor().execute(sql, parameters)

    def executemany(self, sql, parameters):
        return self.cursor().executemany(sql, parameters)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


def get_connection():
    database_url = os.environ.get("DATABASE_URL", "").strip()

    if not database_url:
        if os.environ.get("RENDER") or os.environ.get("MSA_REQUIRE_POSTGRES") == "1":
            raise RuntimeError(
                "PostgreSQL is required in production. "
                "Set DATABASE_URL in the hosting environment."
            )
        conn = sqlite3.connect(str(SQLITE_FILE))
        conn.row_factory = sqlite3.Row
        return conn

    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError(
            "PostgreSQL was requested, but psycopg could not load. "
            "Install requirements.txt in the deployment environment."
        ) from exc

    if database_url.startswith("postgres://"):
        database_url = "postgresql://" + database_url[len("postgres://"):]

    return CompatibleConnection(psycopg.connect(database_url))
